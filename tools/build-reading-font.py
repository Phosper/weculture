"""Build the bundled reading font from Noto Serif SC Regular 2.003.

Requires fonttools[woff] and brotli. Download source and OFL from:
https://github.com/notofonts/noto-cjk/tree/Serif2.003/Serif
Run: python tools/build-reading-font.py path/to/NotoSerifSC-Regular.otf
"""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "weculture-miniprogram" / "pages" / "typography"
FAMILY = "WecultureReadingSerif"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
args = parser.parse_args()

# Cover GB2312, Latin text, plus the app's static UI and smart punctuation.
unicodes = set(range(0x20, 0x100)) | set(range(0x2000, 0x2070))
for first in range(0xA1, 0xF8):
    for second in range(0xA1, 0xFF):
        try:
            unicodes.add(ord(bytes([first, second]).decode("gb2312")))
        except UnicodeDecodeError:
            pass
for extension in ("*.js", "*.wxml"):
    for source in (ROOT / "weculture-miniprogram").rglob(extension):
        unicodes.update(map(ord, source.read_text(encoding="utf-8")))

font = TTFont(args.source, recalcTimestamp=False)
options = subset.Options()
options.hinting = False
options.desubroutinize = True
options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=unicodes)
subsetter.subset(font)
# This is a subset derivative, so keep attribution and use a distinct name.
names = {1: FAMILY, 2: "Regular", 3: FAMILY + "-Regular-2.003", 4: FAMILY + " Regular", 6: FAMILY + "-Regular", 16: FAMILY, 17: "Regular"}
for entry in font["name"].names:
    if entry.nameID in names:
        entry.string = names[entry.nameID].encode(entry.getEncoding())
for name_id, value in names.items():
    font["name"].setName(value, name_id, 3, 1, 0x409)
font.flavor = "woff2"
output = io.BytesIO()
font.save(output)
resource = {
    "family": FAMILY,
    "format": "woff2",
    "upstream": "Noto Serif SC Regular 2.003",
    "sourceURL": "https://raw.githubusercontent.com/notofonts/noto-cjk/Serif2.003/Serif/SubsetOTF/SC/NotoSerifSC-Regular.otf",
    "sourceSHA256": hashlib.sha256(args.source.read_bytes()).hexdigest(),
    "license": "SIL Open Font License 1.1",
    "licenseText": (PACKAGE / "OFL.txt").read_text(encoding="utf-8"),
    "copyright": font["name"].getDebugName(0),
    "glyphCount": len(font.getBestCmap()),
    "base64": base64.b64encode(output.getvalue()).decode("ascii"),
}
target = PACKAGE / "serif-resource.js"
target.write_text("// Generated by tools/build-reading-font.py; licensed under SIL OFL 1.1.\nmodule.exports = " + json.dumps(resource, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"Font: {len(output.getvalue()):,} bytes; resource: {target.stat().st_size:,} bytes; characters: {resource['glyphCount']:,}")
package_size = sum(file.stat().st_size for file in PACKAGE.rglob("*") if file.is_file())
if package_size > 2 * 1024 * 1024:
    raise ValueError(f"Reading-font subpackage exceeds 2 MB: {package_size:,} bytes")
print(f"Reading-font subpackage: {package_size:,} bytes")
